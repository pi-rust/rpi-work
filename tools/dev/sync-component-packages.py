"""Vendor the shared component packages without requiring a sibling checkout at build time.

Author changes in rpi-package, then sync this generated source distribution.
--check compares byte-for-byte and never modifies files.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source-root", type=Path, required=True)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
repository = Path(__file__).resolve().parents[2]
packages = ("rpi-components", "rpi-http-component", "rpi-http-runtime", "rpi-node-api", "rpi-node-core", "rpi-http-node", "rpi-node-host", "rpi-node-launcher", "rpi-http-extension")
expected = {}
for package in packages:
    source = args.source_root.resolve() / "packages" / package
    if not source.is_dir():
        parser.error(f"Missing component package: {source}")
    for path in source.rglob("*"):
        if path.is_symlink():
            parser.error(f"Package symlinks are unsupported: {path}")
        if not path.is_file():
            continue
        relative = path.relative_to(source)
        if relative.parts[0] not in ("src", "ui", "ui-host", "assets", "tests", "Cargo.toml", "README.md"):
            continue
        data = path.read_bytes()
        if path.suffix in (".rs", ".toml", ".md", ".js", ".html"):
            data = data.replace(b"\r\n", b"\n")
        if relative.as_posix() == "Cargo.toml":
            text = data.decode("utf-8")
            text = re.sub(r"edition\.workspace\s*=\s*true", 'edition = "2021"', text)
            text = re.sub(r"rust-version\.workspace\s*=\s*true", 'rust-version = "1.78"', text)
            text = re.sub(r"license\.workspace\s*=\s*true", 'license = "MIT"', text)
            text = re.sub(r"serde_json\.workspace\s*=\s*true", 'serde_json = "1"', text)
            text = re.sub(r"sha2\.workspace\s*=\s*true", 'sha2 = "0.10"', text)
            text = re.sub(r"rpi-plugin-sdk\.workspace\s*=\s*true", 'rpi-plugin-sdk = "=0.3.20"', text)
            text = text.replace("workspace = true", 'version = "1"')
            data = ("# Generated by tools/dev/sync-component-packages.py; author in rpi-package.\n" + text).encode("utf-8")
        expected[Path("vendor") / package / relative] = data

manifest = {"repository": "https://github.com/pi-rust/rpi-package", "packages": list(packages),
            "files": {path.as_posix(): hashlib.sha256(data).hexdigest() for path, data in sorted(expected.items())}}
expected[Path("vendor/component-packages.json")] = (json.dumps(manifest, indent=2) + "\n").encode()
actual = set()
for package in packages:
    target = (repository / "vendor" / package).resolve()
    if target.parent != (repository / "vendor").resolve():
        parser.error("Component destination escaped vendor directory")
    if target.exists():
        actual.update(p.relative_to(repository) for p in target.rglob("*") if p.is_file())
changed = [path for path, data in expected.items()
           if not (repository / path).exists() or (repository / path).read_bytes() != data]
stale = actual - expected.keys()
if args.check:
    if changed or stale:
        raise SystemExit("Component snapshot differs: " + ", ".join(str(p) for p in sorted(set(changed) | stale)))
else:
    for path in changed:
        destination = repository / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(expected[path])
    for path in stale:
        (repository / path).unlink()
print(f"Component snapshot {'verified' if args.check else 'synchronized'} ({len(expected)} files)")
