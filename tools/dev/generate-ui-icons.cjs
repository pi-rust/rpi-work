// Import only static geometry from the same Lucide version as the reference Web.
// Usage: node tools/dev/generate-ui-icons.cjs <path-to-lucide-react> [--check]
// Build/runtime never read that external path. No dependency install/network calls.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const source = path.resolve(process.argv[2] || '');
const check = process.argv.includes('--check');
const pkg = JSON.parse(fs.readFileSync(path.join(source, 'package.json')));
if (pkg.name !== 'lucide-react' || pkg.version !== '0.468.0') throw new Error('Expected reference Web lucide-react 0.468.0');
const map = JSON.parse(fs.readFileSync(path.join(root, 'assets/icons/lucide-map.json')));
const allowedTags = new Set(['path', 'rect', 'circle', 'ellipse', 'line', 'polyline', 'polygon']);
const allowedAttrs = new Set(['d', 'x', 'y', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r', 'x1', 'y1', 'x2', 'y2', 'points']);
const escape = value => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const catalog = {};
for (const name of new Set([...Object.values(map), 'circle-help'])) {
  if (!/^[a-z0-9-]+$/.test(name)) throw new Error('Invalid static icon name');
  const module = fs.readFileSync(path.join(source, 'dist/esm/icons', `${name}.js`), 'utf8');
  const match = module.match(/createLucideIcon\("[^"]+", (\[[\s\S]*?\])\);/);
  if (!match) throw new Error(`No static Lucide nodes: ${name}`);
  // Source is the explicitly supplied, pinned local dependency. Only its array
  // literal is evaluated, with no globals; primitive SVG fields are allowlisted.
  const nodes = vm.runInNewContext(match[1], {}, { timeout: 1000 }).map(([tag, properties]) => {
    if (!allowedTags.has(tag)) throw new Error(`Unsafe SVG element: ${tag}`);
    const attrs = Object.fromEntries(Object.entries(properties).filter(([key]) => key !== 'key'));
    for (const [key, value] of Object.entries(attrs)) {
      if (!allowedAttrs.has(key) || !/^[\da-zA-Z., +\-]+$/.test(String(value))) throw new Error(`Unsafe SVG attribute: ${key}`);
    }
    return [tag, attrs];
  });
  catalog[name] = { nodes, sourceSha256: createHash('sha256').update(module).digest('hex') };
}
const markup = nodes => nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([key, value]) => `${key}="${escape(value)}"`).join(' ')} />`).join('');
const definition = name => `Definition { name: "${name}", svg: r#"${markup(catalog[name].nodes)}"# }`;
const rust = `// Generated by tools/dev/generate-ui-icons.cjs; do not hand-edit.
// Lucide 0.468.0, ISC; see assets/icons/LICENSE.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) struct Definition {
    pub(crate) name: &'static str,
    pub(crate) svg: &'static str,
}

const DEFINITIONS: &[(&str, Definition)] = &[
${Object.entries(map).map(([key, value]) => `    ("${key}", ${definition(value)}),`).join('\n')}
];

pub(crate) fn definition(name: &str) -> Definition {
    DEFINITIONS.iter().find_map(|(key, icon)| (*key == name).then_some(*icon))
        .unwrap_or(${definition('circle-help')})
}
`;
const formattedRust = execFileSync('rustfmt', ['--edition', '2024', '--emit', 'stdout'], { input: rust, encoding: 'utf8' });
function output(file, content) {
  const target = path.join(root, file);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error(`Stale generated asset: ${file}`);
  } else fs.writeFileSync(target, content);
}
output('assets/icons/LICENSE', fs.readFileSync(path.join(source, 'LICENSE'), 'utf8'));
output('assets/icons/lucide-catalog.json', JSON.stringify({ package: 'lucide-react', version: pkg.version, map, catalog }, null, 2) + '\n');
output('apps/work-ui/src/shared/icons.rs', formattedRust.split(String.fromCharCode(13)).join(''));
console.log(`PASS ${check ? 'checked' : 'generated'} ${Object.keys(map).length} semantic icons from pinned Lucide; fallback is circle-help`);
