//! Encrypted envelope for everything a node puts into a QR code.
//!
//! Generic camera and scanner apps should not be able to read a node address,
//! a one-time authorization ticket or the node identity from a screenshot of
//! the screen. Both the address code (`rpi-work-node-address`) and the Android
//! authorization code (`rpi-work-node-auth`) are wrapped in a versioned
//! `rpi-work-qr` envelope before they become QR payloads.
//!
//! The key ships with every client, so this is confidentiality against casual
//! scanning, not an authorization boundary. A ticket stays single-use, expires
//! within 120 seconds and still grants the whole node to whoever redeems it;
//! only show these codes to trusted devices. Older plaintext payloads stay
//! readable so codes generated by previous releases keep working.

use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use sha2::{Digest, Sha256};
use std::sync::atomic::{AtomicU32, Ordering};

/// Shared client key. Rotating it requires a client release on every platform.
const KEY: [u8; 32] = [
    0x5b, 0x2e, 0xd7, 0x41, 0x9c, 0x08, 0xa3, 0x6f, 0x14, 0xb8, 0x7d, 0x32, 0xe9, 0x05, 0x46, 0xcb,
    0x71, 0x9a, 0x2c, 0x63, 0xf0, 0x4d, 0x87, 0x1e, 0xaa, 0x39, 0x54, 0x0d, 0x92, 0xc6, 0x3b, 0x78,
];
const ENVELOPE_TYPE: &str = "rpi-work-qr";
const ENVELOPE_VERSION: u64 = 2;
const MAX_PLAINTEXT: usize = 4096;
const NONCE_LEN: usize = 12;
const TAG_LEN: usize = 16;

static NONCE_COUNTER: AtomicU32 = AtomicU32::new(0);

fn keystream_block(nonce: &[u8; NONCE_LEN], counter: u32) -> [u8; 32] {
    let mut hash = Sha256::new();
    hash.update(KEY);
    hash.update(b"rpi-work-qr-keystream");
    hash.update(nonce);
    hash.update(counter.to_be_bytes());
    hash.finalize().into()
}

fn xor_keystream(nonce: &[u8; NONCE_LEN], bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    for (counter, chunk) in bytes.chunks(32).enumerate() {
        let block = keystream_block(nonce, counter as u32);
        out.extend(chunk.iter().zip(block.iter()).map(|(byte, key)| byte ^ key));
    }
    out
}

fn hmac_sha256(parts: &[&[u8]]) -> [u8; 32] {
    let mut inner_pad = [0x36u8; 64];
    let mut outer_pad = [0x5cu8; 64];
    for (index, byte) in KEY.iter().enumerate() {
        inner_pad[index] ^= byte;
        outer_pad[index] ^= byte;
    }
    let mut inner = Sha256::new();
    inner.update(inner_pad);
    for part in parts {
        inner.update(part);
    }
    let inner = inner.finalize();
    let mut outer = Sha256::new();
    outer.update(outer_pad);
    outer.update(inner);
    outer.finalize().into()
}

fn tag(nonce: &[u8; NONCE_LEN], ciphertext: &[u8]) -> [u8; TAG_LEN] {
    let full = hmac_sha256(&[b"rpi-work-qr-mac", nonce, ciphertext]);
    let mut tag = [0u8; TAG_LEN];
    tag.copy_from_slice(&full[..TAG_LEN]);
    tag
}

fn tags_match(left: &[u8], right: &[u8]) -> bool {
    left.len() == right.len()
        && left
            .iter()
            .zip(right.iter())
            .fold(0u8, |diff, (a, b)| diff | (a ^ b))
            == 0
}

fn nonce() -> [u8; NONCE_LEN] {
    let counter = NONCE_COUNTER.fetch_add(1, Ordering::Relaxed);
    let nanos = web_time::SystemTime::now()
        .duration_since(web_time::UNIX_EPOCH)
        .map(|elapsed| elapsed.as_nanos() as u64)
        .unwrap_or(0);
    let mut nonce = [0u8; NONCE_LEN];
    nonce[..8].copy_from_slice(&nanos.to_be_bytes());
    nonce[8..].copy_from_slice(&counter.to_be_bytes());
    nonce
}

/// Wrap one plaintext payload in the encrypted, versioned QR envelope.
pub fn seal(plaintext: &str) -> String {
    let nonce = nonce();
    let ciphertext = xor_keystream(&nonce, plaintext.as_bytes());
    let tag = tag(&nonce, &ciphertext);
    serde_json::json!({
        "v": ENVELOPE_VERSION,
        "type": ENVELOPE_TYPE,
        "n": URL_SAFE_NO_PAD.encode(nonce),
        "d": URL_SAFE_NO_PAD.encode(&ciphertext),
        "m": URL_SAFE_NO_PAD.encode(tag),
    })
    .to_string()
}

fn decode_field(value: &serde_json::Value, name: &str) -> Result<Vec<u8>, &'static str> {
    let raw = value
        .get(name)
        .and_then(serde_json::Value::as_str)
        .ok_or("二维码缺少加密字段。")?;
    URL_SAFE_NO_PAD
        .decode(raw)
        .map_err(|_| "二维码加密字段无效。")
}

fn looks_like_envelope(raw: &str) -> bool {
    raw.trim_start().starts_with('{') && raw.contains("\"type\"") && raw.contains(ENVELOPE_TYPE)
}

/// Decrypt an encrypted envelope and pass legacy plaintext payloads through.
pub fn open(raw: &str) -> Result<String, &'static str> {
    let raw = raw.trim();
    if raw.len() > MAX_PLAINTEXT * 2 {
        return Err("二维码过长，请重新扫码。");
    }
    if !looks_like_envelope(raw) {
        return Ok(raw.to_string());
    }
    let value: serde_json::Value =
        serde_json::from_str(raw).map_err(|_| "不是有效的加密二维码，请重新扫码。")?;
    if value.get("v").and_then(serde_json::Value::as_u64) != Some(ENVELOPE_VERSION)
        || value.get("type").and_then(serde_json::Value::as_str) != Some(ENVELOPE_TYPE)
    {
        return Err("二维码类型或版本不受支持。");
    }
    let nonce_bytes = decode_field(&value, "n")?;
    if nonce_bytes.len() != NONCE_LEN {
        return Err("二维码加密字段无效。");
    }
    let mut nonce = [0u8; NONCE_LEN];
    nonce.copy_from_slice(&nonce_bytes);
    let ciphertext = decode_field(&value, "d")?;
    if ciphertext.is_empty() || ciphertext.len() > MAX_PLAINTEXT {
        return Err("二维码加密字段无效。");
    }
    let expected = tag(&nonce, &ciphertext);
    let actual = decode_field(&value, "m")?;
    if !tags_match(&expected, &actual) {
        return Err("二维码校验失败，请重新扫码。");
    }
    let plaintext = xor_keystream(&nonce, &ciphertext);
    String::from_utf8(plaintext).map_err(|_| "二维码内容无效。")
}

#[cfg(test)]
mod tests {
    use super::{open, seal};

    #[test]
    fn envelope_round_trips_and_hides_the_payload() {
        let plaintext = r#"{"v":1,"type":"rpi-work-node-auth","address":"http://10.1.2.3:13031/","ticket":"deadbeef","expiresAt":1120,"nodeId":"node-a"}"#;
        let sealed = seal(plaintext);
        assert!(!sealed.contains("10.1.2.3"));
        assert!(!sealed.contains("deadbeef"));
        assert!(!sealed.contains("rpi-work-node-auth"));
        assert_eq!(open(&sealed).unwrap(), plaintext);
        assert_ne!(seal(plaintext), sealed, "each code uses a fresh nonce");
    }

    #[test]
    fn tampered_or_truncated_envelopes_are_rejected() {
        let sealed =
            seal(r#"{"v":1,"type":"rpi-work-node-address","address":"https://example.test"}"#);
        let mut value: serde_json::Value = serde_json::from_str(&sealed).unwrap();
        value["d"] = serde_json::Value::String("AAAA".into());
        assert!(open(&value.to_string()).is_err());
        value["v"] = serde_json::Value::from(3);
        assert!(open(&value.to_string()).is_err());
        assert!(open("{\"v\":2,\"type\":\"rpi-work-qr\"}").is_err());
    }

    #[test]
    fn legacy_plaintext_payloads_still_open() {
        let legacy = r#"{"v":1,"type":"rpi-work-node-address","address":"https://example.test"}"#;
        assert_eq!(open(legacy).unwrap(), legacy);
        assert_eq!(
            open("https://example.test:3030").unwrap(),
            "https://example.test:3030"
        );
    }
}
