// Run with an installed Playwright, or the existing adjacent rpi-web dependency.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(require.resolve('playwright', { paths: [process.cwd(), path.resolve('../rpi-package/packages/rpi-web/frontend')] }));

(async () => {
  const browser = await chromium.launch({ headless:true, executablePath: process.env.CHROME_PATH || 'C:/Users/bigfish/scoop/apps/googlechrome/current/chrome.exe' });
  const errors=[];
  const context=await browser.newContext({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const page=await context.newPage();
  page.on('pageerror',error=>{errors.push(error.message);console.error('PAGE ERROR',error.message);});
  page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
  page.on('requestfailed',req=>errors.push(req.url()));
  const results=[];
  const pass=(text)=>{results.push(text);console.log('PASS '+text);};
  const url=process.env.PROTOTYPE_URL||'http://127.0.0.1:4173/prototype/';
  await page.goto(url);
  await page.getByRole('heading',{name:'为工作台添加深色模式',exact:true}).waitFor();
  fs.mkdirSync('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/prototype-desktop.png',animations:'disabled'});
  await page.locator('#approve').click();
  await page.getByText('验证完成 · 演示结果',{exact:true}).waitFor();
  assert.match(await page.locator('#task-status').innerText(),/已完成/);
  pass('single-use approval updates final demo state');
  await page.getByRole('tab',{name:/变更/}).click();
  await page.locator('[data-change-index="1"]').click();
  assert.match(await page.locator('.selected-file-path').innerText(),/src\/components\/theme.rs/);
  pass('file selection changes visible diff');
  await page.getByRole('tab',{name:'对话',exact:true}).click();
  assert.equal(await page.getByRole('tab').count(),2);
  await page.locator('#call-shell > summary').click();
  assert.match(await page.locator('#call-shell .call-output').innerText(),/12 passed; 0 failed/);
  await page.locator('#timeline-plan > summary').click();
  assert.equal(await page.locator('#timeline-plan li').count(),3);
  pass('command output and plan stay inline in the conversation');
  await page.locator('#session-options').click();await page.locator('#reset-demo').click();await page.locator('#reject').click();
  assert.match(await page.locator('#task-status').innerText(),/等待下一步/);
  pass('rejection keeps task awaiting next instruction');
  await page.locator('#new-task').click();await page.locator('#create-task').click();
  assert.equal(await page.locator('#modal').evaluate(e=>e.open),true);
  await page.locator('#new-title').fill('验证新的 Agent 任务');await page.locator('#create-task').click();
  assert.equal(await page.locator('#task-title').innerText(),'验证新的 Agent 任务');
  await page.locator('#prompt').fill('先给我一个计划');await page.locator('#send-button').click();
  await page.getByRole('button',{name:'停止生成',exact:true}).click();await page.getByRole('button',{name:'发送消息',exact:true}).waitFor();
  assert.match(await page.locator('#task-body').innerText(),/已停止演示生成/);
  await page.locator('#prompt').fill('<img src=x onerror=alert(1)>');await page.locator('#send-button').click();
  await page.getByText(/演示回复：收到你的补充/).waitFor();await page.getByRole('button',{name:'发送消息',exact:true}).waitFor();
  assert.equal(await page.locator('#task-body img').count(),0);
  pass('new task validation, send/stop, and safe text rendering');
  await page.locator('#model-button').click();await page.locator('[data-model="OpenAI"]').click();
  assert.equal(await page.locator('#model-label').innerText(),'OpenAI');
  await page.locator('#mode-button').click();assert.equal(await page.locator('#mode-label').innerText(),'规划');
  pass('model and execution mode selection');
  await page.locator('#search-button').click();await page.locator('#search-input').fill('验证新的');
  assert.equal(await page.locator('.search-result').count(),1);
  await page.locator('.search-result').click();
  await page.locator('.primary-nav [data-nav="extensions"]').click();
  const toggle=page.getByRole('switch',{name:'切换 rpi-mcp-adapter',exact:true});
  await toggle.click();assert.equal(await toggle.getAttribute('aria-checked'),'true');
  await page.locator('.primary-nav [data-nav="devices"]').click();
  await page.locator('#pair-device').click();await page.locator('.pair-invite-demo > summary').click();await page.locator('#simulate-pair').click();await page.locator('#pair-verified').check();await page.locator('#approve-pair').click();
  await page.getByRole('heading',{name:'我的手机',exact:true}).waitFor();
  await page.locator('#unpair').click();assert.equal(await page.getByRole('heading',{name:'我的手机',exact:true}).count(),0);
  pass('search, extension toggles, pairing and revocation simulations');
  await page.locator('#settings-button').click();await page.locator('#theme-select').selectOption('dark');
  assert.equal(await page.locator('body').evaluate(e=>e.classList.contains('theme-dark')),true);
  await page.locator('#theme-select').selectOption('light');await page.getByRole('button',{name:'完成',exact:true}).click();
  pass('light/dark settings');
  await page.locator('.primary-nav [data-nav="workspace"]').click();
  await page.locator('[data-session="dark"]').click();await page.locator('#session-options').click();await page.locator('#reset-demo').click();
  for(const width of [1440,1024,768,390,375]){
    await page.setViewportSize({width,height:900});
    const dimensions=await page.evaluate(()=>({viewport:innerWidth,scroll:document.documentElement.scrollWidth}));
    assert.ok(dimensions.scroll<=dimensions.viewport,`horizontal overflow at ${width}`);
  }
  pass('no document overflow at 375, 390, 768, 1024, 1440px');
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await page.locator('#approve').scrollIntoViewIfNeeded();
  await page.screenshot({path:'artifacts/prototype-mobile.png',animations:'disabled'});
  const sidebarRight=await page.locator('.sidebar').evaluate(e=>e.getBoundingClientRect().right);
  assert.ok(sidebarRight<=0,'mobile sidebar is fully offscreen when closed');
  await page.locator('#menu-toggle').click();await page.locator('.primary-nav [data-nav="devices"]').click();
  assert.equal(await page.locator('.sidebar').evaluate(e=>e.classList.contains('open')),false);
  await page.locator('#menu-toggle').click();await page.locator('.primary-nav [data-nav="workspace"]').click();
  await page.locator('#context-toggle').click();assert.equal(await page.locator('#inspector').isVisible(),true);await page.locator('#context-close').click();
  pass('mobile navigation and context drawer');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#preview-toggle').click();
  assert.equal(await page.locator('#app').evaluate(e=>Math.round(e.getBoundingClientRect().width)),420);
  await page.locator('#preview-toggle').click();
  pass('desktop phone-preview toggle');
  await page.goto('file:///'+path.resolve('prototype/index.html').replace(/\\/g,'/'));
  await page.getByRole('heading',{name:'为工作台添加深色模式',exact:true}).waitFor();
  pass('standalone file:// opening without a dev server');
  assert.deepEqual(errors,[]);
  pass('no JavaScript/console/resource errors');
  fs.writeFileSync('artifacts/prototype-validation.json',JSON.stringify({date:'2026-10-23',browser:await browser.version(),results,errors},null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
